'use strict';
/*
 * scan-schema.js — the scan record declared ONCE (producer ≡ consumer).
 *
 * Imported by log-scan.js (writer), scan-history.js (reader), and verify-scan-logging.js
 * (drift guard). The whitelist IS `FIELDS` — a mechanism, not a second definition. Mirrors
 * the xp-lib.js contract: one file owns the shape, everyone else reads it.
 *
 * Boundary-safe by construction: there is NO `post_text` key. Client copy has nowhere to live.
 */

// ── The record shape (whitelist) ─────────────────────────────────────────────
// Every key the writer is allowed to persist. Anything not here is dropped on projection.
const FIELDS = Object.freeze([
  'scan_id', 'schema_version', 'ts', 'client_slug', 'mode', 'project', 'platform',
  'caller', 'overall', 'gate', 'dims', 'voice_audit', 'top_fix_tags',
  'image_version', 'post_excerpt', 'post_ref',
]);

// The 7 virality dimensions — exactly these, no 8th. Read explicitly (never spread) to block
// prototype pollution via a crafted `dims` object.
const DIM_KEYS = Object.freeze([
  'hook_strength', 'curiosity_specificity', 'emotional_charge', 'share_worthiness',
  'voice_match', 'polarity', 'platform_fit',
]);

const ENUMS = Object.freeze({
  mode: Object.freeze(['self', 'client']),
  caller: Object.freeze(['post-grader-v2', 'post-writer-v2', 'repurpose-v2']),
  gate: Object.freeze(['PASS', 'REVISE', 'BLOCKED-ethics', 'BLOCKED-compliance']),
});

// Client-mode top_fix_tags MUST come from this closed vocabulary (self mode = free text).
const CLIENT_FIX_VOCAB = Object.freeze([
  'weak-hook', 'no-curiosity-gap', 'low-emotion', 'not-shareable', 'voice-drift',
  'off-polarity', 'platform-misfit', 'cta-buried', 'compliance-risk', 'off-wedge',
]);

// Fields the caller MUST supply (scan_id is caller-minted, one per grading attempt — never
// auto-generated by the writer, so a re-grade climbing loop keeps distinct records).
const REQUIRED = Object.freeze([
  'scan_id', 'client_slug', 'mode', 'caller', 'overall', 'dims', 'gate',
]);

// ── Charset guards (scan_id becomes a filename; slug/token feed path joins) ───
const SLUG_RE = /^[a-z0-9][a-z0-9-]{0,63}$/;
const TOKEN_RE = /^[A-Za-z0-9._-]{1,64}$/;
const UUID_RE = /^[0-9a-f]{8}-[0-9a-f]{4}-[1-5][0-9a-f]{3}-[89ab][0-9a-f]{3}-[0-9a-f]{12}$/i;

const SCHEMA_VERSION = 1;

function isNum(n) { return typeof n === 'number' && Number.isFinite(n); }
function inRange(n) { return isNum(n) && n >= 0 && n <= 10; }

/*
 * validate(rec) → { ok:true } | { ok:false, errors:[…] }
 * Required-presence + type + enum + range only. Charset/path-traversal validation lives in
 * log-scan.js (step 3) because it needs os.homedir()/path resolution the schema stays free of.
 */
function validate(rec) {
  const errors = [];
  if (rec === null || typeof rec !== 'object') return { ok: false, errors: ['record-not-object'] };

  for (const k of REQUIRED) {
    if (rec[k] === undefined || rec[k] === null) errors.push(`missing:${k}`);
  }

  if (rec.scan_id !== undefined && rec.scan_id !== null && !UUID_RE.test(String(rec.scan_id))) {
    errors.push('scan_id-not-uuid');
  }
  if (rec.client_slug !== undefined && rec.client_slug !== null && !SLUG_RE.test(String(rec.client_slug))) {
    errors.push('client_slug-bad-charset');
  }
  if (rec.mode !== undefined && rec.mode !== null && !ENUMS.mode.includes(rec.mode)) {
    errors.push('mode-not-enum');
  }
  if (rec.caller !== undefined && rec.caller !== null && !ENUMS.caller.includes(rec.caller)) {
    errors.push('caller-not-enum');
  }
  if (rec.gate !== undefined && rec.gate !== null && !ENUMS.gate.includes(rec.gate)) {
    errors.push('gate-not-enum');
  }
  if (rec.overall !== undefined && rec.overall !== null && !inRange(rec.overall)) {
    errors.push('overall-out-of-range');
  }

  // dims: object with EXACTLY the 7 DIM_KEYS, each a number in [0,10].
  const d = rec.dims;
  if (d === undefined || d === null || typeof d !== 'object' || Array.isArray(d)) {
    if (!errors.includes('missing:dims')) errors.push('dims-not-object');
  } else {
    const keys = Object.keys(d);
    if (keys.length !== DIM_KEYS.length) errors.push('dims-wrong-key-count');
    for (const k of DIM_KEYS) {
      if (!(k in d)) errors.push(`dims-missing:${k}`);
      else if (!inRange(d[k])) errors.push(`dims-out-of-range:${k}`);
    }
    for (const k of keys) {
      if (!DIM_KEYS.includes(k)) errors.push(`dims-extra-key:${k}`);
    }
  }

  return errors.length ? { ok: false, errors } : { ok: true };
}

module.exports = {
  FIELDS, DIM_KEYS, ENUMS, REQUIRED, CLIENT_FIX_VOCAB,
  SLUG_RE, TOKEN_RE, UUID_RE, SCHEMA_VERSION, validate,
};
